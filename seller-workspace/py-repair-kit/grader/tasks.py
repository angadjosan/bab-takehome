"""Task discovery, workspace materialisation, path policy and pytest execution.

Starting-state mechanism ("overlay"): a task's starting workspace is a copy of
``src/`` with every file under ``tasks/<id>/overlay/`` copied on top of it at
the same relative path (overlay files replace or add files). The agent
workspace additionally receives ``tasks/<id>/visible_tests/`` as
``visible_tests/`` and a generated ``pytest.ini``. Hidden tests
(``tasks/<id>/tests/``) are never copied into the agent workspace.
"""

from __future__ import annotations

import fnmatch
import hashlib
import json
import os
import re
import shlex
import shutil
import signal
import subprocess
import sys
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Iterable, Optional, Sequence

KIT_ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = KIT_ROOT / "src"
GRADER_VERSION = "1.0.0"
ENVIRONMENT_VERSION = "py-repair-kit@1.0.0"

PYTEST_INI = "[pytest]\n# generated by py-repair-kit; not editable by the agent\naddopts =\n"
DENY_BASENAMES = {"conftest.py", "sitecustomize.py", "usercustomize.py", "pytest.ini"}
MAX_WRITE_BYTES = 256 * 1024
_TASK_ID_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
_IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", ".pytest_cache", ".DS_Store")


class TaskError(Exception):
    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code
        self.message = message


def default_task_roots() -> list[Path]:
    env = os.environ.get("PYREPAIR_TASK_ROOTS")
    if env:
        return [Path(p) for p in env.split(os.pathsep) if p]
    return [p for p in (KIT_ROOT / "tasks", KIT_ROOT / "audit-tasks") if p.is_dir()]


@dataclass(frozen=True)
class Task:
    task_id: str
    dir: Path
    spec: dict

    @property
    def overlay_dir(self) -> Path:
        return self.dir / self.spec.get("startingState", {}).get("overlayDir", "overlay/").rstrip("/")

    @property
    def hidden_tests_dir(self) -> Path:
        return self.dir / self.spec.get("hiddenTestsDir", "tests/").rstrip("/")

    @property
    def visible_tests_dir(self) -> Path:
        return self.dir / self.spec.get("visibleTestsDir", "visible_tests/").rstrip("/")

    @property
    def editable(self) -> list[str]:
        return list(self.spec.get("editableFiles", []))

    @property
    def action_budget(self) -> int:
        return int(self.spec.get("actionBudget", 12))

    @property
    def time_budget_sec(self) -> float:
        return float(self.spec.get("timeBudgetSec", 600))

    @property
    def grade_timeout_sec(self) -> float:
        return float(self.spec.get("gradeTimeoutSec", 120))

    @property
    def visible_cmd(self) -> str:
        return self.spec.get("visibleTestCmd", "python -m pytest -q -p no:cacheprovider visible_tests")

    def visible_argv(self) -> list[str]:
        argv = shlex.split(self.visible_cmd)
        if argv and argv[0] in ("python", "python3"):
            argv[0] = sys.executable
        return argv


def load_task(task_id: str, roots: Optional[Sequence[Path]] = None) -> Task:
    if not isinstance(task_id, str) or not _TASK_ID_RE.match(task_id):
        raise TaskError("bad_task_id", f"invalid task id: {task_id!r}")
    for root in roots or default_task_roots():
        tdir = Path(root) / task_id
        spec_path = tdir / "task.json"
        if spec_path.is_file():
            spec = json.loads(spec_path.read_text(encoding="utf-8"))
            if spec.get("taskId") != task_id:
                raise TaskError("bad_task", f"{spec_path}: taskId mismatch")
            return Task(task_id, tdir.resolve(), spec)
    raise TaskError("unknown_task", f"task not found: {task_id}")


def list_task_dirs(roots: Optional[Sequence[Path]] = None) -> list[Path]:
    out = []
    for root in roots or default_task_roots():
        root = Path(root)
        if root.is_dir():
            out.extend(sorted(p for p in root.iterdir() if (p / "task.json").is_file()))
    return out


def _copy_tree(src: Path, dst: Path) -> None:
    if src.is_dir():
        shutil.copytree(src, dst, dirs_exist_ok=True, ignore=_IGNORE)


def materialize_base(task: Task, dest: Path) -> None:
    """Starting state of the library: src/ + overlay."""
    dest.mkdir(parents=True, exist_ok=True)
    _copy_tree(SRC_DIR, dest)
    _copy_tree(task.overlay_dir, dest)


def materialize_workspace(task: Task, dest: Path) -> None:
    """Agent workspace: starting state + visible tests + pytest.ini (no hidden tests)."""
    materialize_base(task, dest)
    _copy_tree(task.visible_tests_dir, dest / "visible_tests")
    (dest / "pytest.ini").write_text(PYTEST_INI, encoding="utf-8")


def normalize_relpath(rel: object) -> str:
    """Validate a workspace-relative POSIX path; raise TaskError if unsafe."""
    if not isinstance(rel, str) or not rel or "\x00" in rel or "\\" in rel:
        raise TaskError("bad_path", f"invalid path: {rel!r}")
    p = PurePosixPath(rel)
    if p.is_absolute() or any(part in ("..", "") for part in p.parts):
        raise TaskError("bad_path", f"path must be relative and stay inside the workspace: {rel!r}")
    parts = [x for x in p.parts if x != "."]
    return "/".join(parts) if parts else "."


def resolve_in(root: Path, rel: str) -> Path:
    rel = normalize_relpath(rel)
    root = root.resolve()
    target = (root / rel).resolve() if rel != "." else root
    if target != root and root not in target.parents:
        raise TaskError("bad_path", f"path escapes the workspace: {rel!r}")
    return target


def is_editable(task: Task, rel: str) -> bool:
    rel = normalize_relpath(rel)
    parts = rel.split("/")
    if parts[-1] in DENY_BASENAMES or "__pycache__" in parts:
        return False
    for pattern in task.editable:
        pparts = pattern.split("/")
        if len(pparts) == len(parts) and all(fnmatch.fnmatchcase(a, b) for a, b in zip(parts, pparts)):
            return True
    return False


def iter_files(root: Path) -> list[str]:
    """Sorted relative paths of regular files (no symlinks, no __pycache__)."""
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in ("__pycache__", ".pytest_cache"))
        for name in filenames:
            full = Path(dirpath) / name
            if full.is_symlink() or not full.is_file() or name.endswith(".pyc"):
                continue
            out.append(full.relative_to(root).as_posix())
    return sorted(out)


def digest_files(root: Path, rels: Iterable[str]) -> str:
    h = hashlib.sha256()
    for rel in sorted(rels):
        h.update(rel.encode() + b"\0" + hashlib.sha256((root / rel).read_bytes()).digest())
    return "0x" + h.hexdigest()


def _child_env(cwd: Path) -> dict:
    tmp = tempfile.gettempdir()
    return {
        "PATH": os.environ.get("PATH", "/usr/local/bin:/usr/bin:/bin"),
        "PYTHONPATH": str(cwd),
        "PYTHONHASHSEED": "0",
        "PYTHONDONTWRITEBYTECODE": "1",
        "PYTHONUTF8": "1",
        "PYTHONNOUSERSITE": "1",
        "HOME": tmp,
        "TMPDIR": tmp,
        "TZ": "UTC",
        "LC_ALL": "C.UTF-8",
        "NO_COLOR": "1",
    }


def run_command(argv: list[str], cwd: Path, timeout: float) -> dict:
    """Run argv in its own process group; kill the whole group on timeout."""
    started = time.monotonic()
    proc = subprocess.Popen(
        argv,
        cwd=str(cwd),
        env=_child_env(cwd),
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        start_new_session=True,
    )
    timed_out = False
    try:
        out, _ = proc.communicate(timeout=max(1.0, timeout))
    except subprocess.TimeoutExpired:
        timed_out = True
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        out, _ = proc.communicate()
    return {
        "exitCode": proc.returncode,
        "timedOut": timed_out,
        "output": out.decode("utf-8", errors="replace"),
        "durationSec": round(time.monotonic() - started, 3),
    }


def tail(text: str, limit: int) -> str:
    return text if len(text) <= limit else "...[truncated]...\n" + text[-limit:]
